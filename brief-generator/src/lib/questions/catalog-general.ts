import type { Question, QuestionOption } from './types';

/** Azúcar para no repetir los campos vacíos en cada pregunta. */
export function q(
  partial: Omit<Question, 'options' | 'conditions' | 'required' | 'builtIn'> &
    Partial<Pick<Question, 'options' | 'conditions' | 'required'>>,
): Question {
  return {
    options: [],
    conditions: [],
    required: false,
    builtIn: true,
    ...partial,
  };
}

export function opts(...pairs: (string | [string, string])[]): QuestionOption[] {
  return pairs.map((p) =>
    Array.isArray(p) ? { value: p[0], label: p[1] } : { value: slug(p), label: p },
  );
}

export function slug(text: string): string {
  return text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .slice(0, 40);
}

